import { getSupabase } from "@/lib/supabase";
import Link from "next/link";
import { AlertTriangle, Building2, Briefcase, TrendingUp, Gift, ArrowUpRight } from "lucide-react";

export const dynamic = "force-dynamic";

type ProcurementFlag = {
  id: string;
  public_text: string | null;
  mp_name: string | null;
  mp_party: string | null;
  tender_company: string | null;
  disclosure_counterparty: string | null;
  disclosure_category: string | null;
  tender_amount_zar: string | null;
  award_date: string | null;
  department: string | null;
  tender_title: string | null;
  match_reason: string | null;
  mp_id: string;
};

const CATEGORY_META: Record<string, { label: string; color: string; bg: string }> = {
  shareholding:    { label: "Shareholding",   color: "text-indigo-700", bg: "bg-indigo-50" },
  directorship:    { label: "Directorship",   color: "text-blue-700",   bg: "bg-blue-50" },
  consultancy:     { label: "Consultancy",    color: "text-cyan-700",   bg: "bg-cyan-50" },
  paid_employment: { label: "Employment",     color: "text-emerald-700",bg: "bg-emerald-50" },
  gift_hospitality:{ label: "Gift/Hospitality",color: "text-amber-700", bg: "bg-amber-50" },
  other:           { label: "Other Interest", color: "text-slate-600",  bg: "bg-slate-50" },
};

function fmt(zar: string | null): string {
  if (!zar) return "—";
  const n = parseFloat(zar);
  if (n >= 1e9) return `R${(n / 1e9).toFixed(1)}B`;
  if (n >= 1e6) return `R${(n / 1e6).toFixed(1)}M`;
  if (n >= 1e3) return `R${(n / 1e3).toFixed(0)}K`;
  return `R${n.toLocaleString()}`;
}

export default async function TendersPage() {
  const supabase = getSupabase();
  const { data: flags, error } = await supabase
    .from("v_procurement_flags_public")
    .select("*")
    .order("tender_amount_zar", { ascending: false }) as unknown as { data: ProcurementFlag[] | null; error: unknown };

  if (error) throw new Error(`Failed to load procurement flags: ${(error as { message?: string }).message ?? String(error)}`);

  // Group by company for a cleaner view
  const byCompany: Record<string, ProcurementFlag[]> = {};
  for (const flag of flags ?? []) {
    const key = flag.tender_company ?? "Unknown";
    (byCompany[key] ??= []).push(flag);
  }

  const totalValue = (flags ?? []).reduce((sum, f) => {
    const unique = new Set<string>();
    // only count each tender once
    const key = `${f.tender_company}|${f.award_date}`;
    if (!unique.has(key)) { unique.add(key); return sum + parseFloat(f.tender_amount_zar ?? "0"); }
    return sum;
  }, 0);

  return (
    <main className="container mx-auto py-10 px-4 max-w-5xl">
      {/* Header */}
      <div className="mb-8">
        <div className="flex items-center gap-2 mb-1">
          <AlertTriangle className="text-amber-500" size={20} />
          <h1 className="text-3xl font-bold tracking-tight">Follow the Tender</h1>
        </div>
        <p className="text-slate-500 text-sm mt-1 max-w-2xl">
          Cross-reference between government tender awards and MPs' declared financial interests.
          A match means an MP has disclosed an interest in a company that received a government contract —
          not necessarily wrongdoing, but worth scrutiny.
        </p>
      </div>

      {/* Stats strip */}
      <div className="grid grid-cols-3 gap-4 mb-8">
        <div className="rounded-xl border border-stone-200 bg-white px-5 py-4 shadow-sm">
          <p className="text-xs font-medium uppercase tracking-widest text-slate-400 mb-1">Flags found</p>
          <p className="text-3xl font-bold text-slate-900">{(flags ?? []).length}</p>
        </div>
        <div className="rounded-xl border border-stone-200 bg-white px-5 py-4 shadow-sm">
          <p className="text-xs font-medium uppercase tracking-widest text-slate-400 mb-1">MPs involved</p>
          <p className="text-3xl font-bold text-slate-900">
            {new Set((flags ?? []).map((f) => f.mp_id)).size}
          </p>
        </div>
        <div className="rounded-xl border border-stone-200 bg-white px-5 py-4 shadow-sm">
          <p className="text-xs font-medium uppercase tracking-widest text-slate-400 mb-1">Tender coverage</p>
          <p className="text-3xl font-bold text-slate-900">171</p>
          <p className="text-[11px] text-slate-400 mt-0.5">awards in DB (2026)</p>
        </div>
      </div>

      {/* Disclaimer */}
      <div className="mb-6 rounded-lg border border-amber-200 bg-amber-50 px-4 py-3 text-sm text-amber-800">
        <strong>Note:</strong> These flags are automatically generated by name-matching algorithms.
        A flag indicates a <em>declared interest</em> in a company, not corruption. MPs are required by law
        to declare such interests. The absence of a flag does not mean no conflict exists.
      </div>

      {/* Flags grouped by company */}
      {Object.keys(byCompany).length === 0 ? (
        <div className="rounded-xl border-2 border-dashed border-stone-200 py-16 text-center text-slate-400">
          No procurement matches found yet. More tender data will improve coverage.
        </div>
      ) : (
        <div className="space-y-6">
          {Object.entries(byCompany).map(([company, companyFlags]) => {
            const sample = companyFlags![0];
            return (
              <section key={company} className="rounded-xl border border-stone-200 bg-white shadow-sm overflow-hidden">
                {/* Company header */}
                <div className="flex items-center justify-between gap-4 border-b border-stone-100 bg-stone-50 px-5 py-3">
                  <div className="flex items-center gap-3">
                    <Building2 size={16} className="text-slate-500 shrink-0" />
                    <div>
                      <span className="font-semibold text-slate-900">{company}</span>
                      <span className="ml-2 text-xs text-slate-400">{sample.department}</span>
                    </div>
                  </div>
                  <div className="flex items-center gap-4 shrink-0">
                    <div className="text-right">
                      <p className="text-xs text-slate-400">Award value</p>
                      <p className="text-sm font-bold text-slate-800">{fmt(sample.tender_amount_zar)}</p>
                    </div>
                    <div className="text-right">
                      <p className="text-xs text-slate-400">Award date</p>
                      <p className="text-sm font-medium text-slate-700">
                        {sample.award_date
                          ? new Date(sample.award_date).toLocaleDateString("en-ZA", { year: "numeric", month: "short", day: "numeric" })
                          : "—"}
                      </p>
                    </div>
                  </div>
                </div>

                {/* MP rows */}
                <div className="divide-y divide-stone-100">
                  {companyFlags!.map((flag) => {
                    const cat = CATEGORY_META[flag.disclosure_category ?? "other"] ?? CATEGORY_META.other;
                    return (
                      <div key={flag.id} className="flex items-center gap-4 px-5 py-3">
                        <div className="flex-1 min-w-0">
                          <div className="flex items-center gap-2 flex-wrap">
                            <Link
                              href={`/mps/${flag.mp_id}`}
                              className="font-medium text-sm text-slate-900 hover:text-teal-700 hover:underline flex items-center gap-1"
                            >
                              {flag.mp_name ?? "Unknown MP"}
                              <ArrowUpRight size={11} className="opacity-50" />
                            </Link>
                            {flag.mp_party && (
                              <span className="text-[11px] text-slate-500 bg-slate-100 rounded px-1.5 py-0.5">
                                {flag.mp_party}
                              </span>
                            )}
                          </div>
                          <p className="text-xs text-slate-500 mt-0.5">
                            Declared: <span className="italic">{flag.disclosure_counterparty}</span>
                          </p>
                        </div>
                        <span className={`shrink-0 rounded-full px-2.5 py-1 text-[11px] font-medium ${cat.bg} ${cat.color}`}>
                          {cat.label}
                        </span>
                      </div>
                    );
                  })}
                </div>
              </section>
            );
          })}
        </div>
      )}

      <p className="mt-8 text-xs text-slate-400 text-center">
        Sources: Parliament Register of Members' Interests · National Treasury OCDS API ·
        Data coverage: Jan–Jul 2026. More historical awards being ingested.
      </p>
    </main>
  );
}
